CREATE TABLE staff_execution_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, booking_id BIGINT NOT NULL REFERENCES bookings(id),
 assignment_id BIGINT NOT NULL REFERENCES booking_assignments(id), staff_id BIGINT NOT NULL,
 status VARCHAR(30) NOT NULL CHECK(status IN ('EN_ROUTE','IN_PROGRESS','COMPLETED','CANCELLED','NO_SHOW')),
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(), source VARCHAR(20) NOT NULL, note TEXT NOT NULL DEFAULT '', UNIQUE(assignment_id,status)
);
CREATE TABLE forgotten_job_remediations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, booking_id BIGINT NOT NULL REFERENCES bookings(id),
 assignment_id BIGINT NOT NULL UNIQUE REFERENCES booking_assignments(id), staff_id BIGINT NOT NULL, customer_id BIGINT NOT NULL,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(), finance_synced BOOLEAN NOT NULL DEFAULT false, voucher_synced BOOLEAN NOT NULL DEFAULT false,
 voucher_code VARCHAR(60), last_error TEXT, checked_at TIMESTAMPTZ NOT NULL DEFAULT 'epoch', evidence TEXT NOT NULL
);
CREATE FUNCTION protect_execution_events() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Execution audit events are immutable'; END $$;
CREATE TRIGGER protect_execution_events BEFORE UPDATE OR DELETE ON staff_execution_events FOR EACH ROW EXECUTE FUNCTION protect_execution_events();
CREATE INDEX ix_execution_booking ON staff_execution_events(booking_id,occurred_at);
