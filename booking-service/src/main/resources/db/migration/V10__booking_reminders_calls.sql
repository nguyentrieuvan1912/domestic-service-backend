CREATE TABLE booking_reminder_deliveries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 assignment_id BIGINT NOT NULL REFERENCES booking_assignments(id),
 starts_at TIMESTAMPTZ NOT NULL,
 minutes_before INTEGER NOT NULL CHECK(minutes_before IN (60,30)),
 sent_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(assignment_id,starts_at,minutes_before)
);
CREATE TABLE booking_calls (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 conversation_id BIGINT NOT NULL REFERENCES conversations(id),
 caller_id BIGINT NOT NULL,
 callee_id BIGINT NOT NULL,
 room_name VARCHAR(120) NOT NULL UNIQUE,
 request_key VARCHAR(160) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'RINGING' CHECK(status IN ('RINGING','ACCEPTED','ENDED','DECLINED','MISSED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 accepted_at TIMESTAMPTZ,
 ended_at TIMESTAMPTZ,
 room_closed_at TIMESTAMPTZ,
 UNIQUE(caller_id,request_key)
);
CREATE UNIQUE INDEX uq_booking_call_active ON booking_calls(conversation_id) WHERE status IN ('RINGING','ACCEPTED');
