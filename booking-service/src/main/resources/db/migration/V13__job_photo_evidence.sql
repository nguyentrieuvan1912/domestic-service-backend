CREATE TABLE booking_job_evidence (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 booking_id BIGINT NOT NULL REFERENCES bookings(id),
 assignment_id BIGINT NOT NULL REFERENCES booking_assignments(id),
 staff_id BIGINT NOT NULL,
 stage VARCHAR(10) NOT NULL CHECK(stage IN ('BEFORE','AFTER')),
 request_key VARCHAR(160) NOT NULL,
 mime_type VARCHAR(30) NOT NULL CHECK(mime_type IN ('image/jpeg','image/png')),
 image_data BYTEA NOT NULL CHECK(octet_length(image_data) BETWEEN 1 AND 2097152),
 thumbnail_data BYTEA NOT NULL,
 sha256 VARCHAR(64) NOT NULL,
 width INTEGER NOT NULL CHECK(width>0), height INTEGER NOT NULL CHECK(height>0),
 message_id BIGINT NOT NULL UNIQUE REFERENCES messages(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(booking_id,staff_id,request_key), UNIQUE(booking_id,staff_id,sha256)
);
CREATE INDEX ix_job_evidence_booking ON booking_job_evidence(booking_id,staff_id,stage,id);
CREATE FUNCTION reject_job_evidence_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Job evidence is immutable and retained for complaint review'; END $$;
CREATE TRIGGER job_evidence_immutable BEFORE UPDATE OR DELETE ON booking_job_evidence
 FOR EACH ROW EXECUTE FUNCTION reject_job_evidence_mutation();
CREATE FUNCTION require_job_completion_evidence() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.execution_status='COMPLETED' AND OLD.execution_status IS DISTINCT FROM 'COMPLETED' THEN
  IF NOT EXISTS(SELECT 1 FROM booking_job_evidence WHERE assignment_id=NEW.id AND staff_id=NEW.staff_id AND stage='BEFORE')
   OR NOT EXISTS(SELECT 1 FROM booking_job_evidence WHERE assignment_id=NEW.id AND staff_id=NEW.staff_id AND stage='AFTER') THEN
   RAISE EXCEPTION 'Completion requires at least one BEFORE and one AFTER evidence photo for this staff assignment' USING ERRCODE='23514',CONSTRAINT='job_completion_evidence';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER job_completion_evidence BEFORE UPDATE OF execution_status ON booking_assignments
 FOR EACH ROW EXECUTE FUNCTION require_job_completion_evidence();
