CREATE TABLE ai_chat_turns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES ai_conversations(id),
    client_key VARCHAR(160) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    attempt_key VARCHAR(36) NOT NULL,
    lease_until TIMESTAMPTZ NOT NULL,
    response_id BIGINT REFERENCES ai_messages(id),
    UNIQUE (conversation_id, client_key)
);
