CREATE TABLE catalog_semantic_vectors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_type VARCHAR(10) NOT NULL CHECK (resource_type IN ('SERVICE','PACKAGE')),
    resource_id BIGINT NOT NULL,
    service_id BIGINT NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    embedding_model VARCHAR(100) NOT NULL,
    dimension INTEGER NOT NULL CHECK (dimension>0),
    content TEXT NOT NULL,
    embedding JSONB NOT NULL CHECK (jsonb_typeof(embedding)='array'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(resource_type,resource_id,content_hash,embedding_model)
);
CREATE INDEX ix_catalog_semantic_service ON catalog_semantic_vectors(service_id);
