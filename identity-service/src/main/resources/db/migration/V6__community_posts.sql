-- Class Diagram1.jpg: User 1 -> 0..* CommunityPost.
-- Keep account ownership in Identity; no cross-database foreign keys.
CREATE TABLE community_posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    content TEXT NOT NULL CHECK (btrim(content) <> ''),
    media_urls JSONB NOT NULL DEFAULT '[]'::jsonb
        CHECK (jsonb_typeof(media_urls) = 'array'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_community_posts_user_created ON community_posts(user_id, created_at DESC);
COMMENT ON TABLE community_posts IS 'CommunityPost owned by one User; revised class diagram 2026-10-13';
COMMENT ON COLUMN community_posts.media_urls IS 'JSON array of media URLs; maps to CommunityPost.mediaUrls';
