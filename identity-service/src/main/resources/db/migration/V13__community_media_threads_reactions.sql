 PRIMARY KEY(comment_id,user_id)
);
CREATE TABLE community_media (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 post_id BIGINT REFERENCES community_posts(id),
 public_id VARCHAR(200) NOT NULL UNIQUE,
 resource_type VARCHAR(10) NOT NULL CHECK(resource_type IN ('image','video')),
 status VARCHAR(12) NOT NULL DEFAULT 'RESERVED' CHECK(status IN ('RESERVED','READY','ATTACHED')),
 secure_url TEXT,
 bytes BIGINT,
 width INTEGER,
 height INTEGER,
 duration DOUBLE PRECISION,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 expires_at TIMESTAMPTZ NOT NULL DEFAULT now()+interval '15 minutes',
 CHECK((status='ATTACHED')=(post_id IS NOT NULL))
);
CREATE INDEX ix_community_media_user ON community_media(user_id,created_at);
