ALTER TABLE community_posts ADD COLUMN status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','PUBLISHED','HIDDEN'));
ALTER TABLE community_posts ADD COLUMN moderation_note TEXT;
ALTER TABLE community_posts ADD COLUMN reviewed_by BIGINT REFERENCES users(id);
CREATE TABLE community_comments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 post_id BIGINT NOT NULL REFERENCES community_posts(id),
 user_id BIGINT NOT NULL REFERENCES users(id),
 content TEXT NOT NULL CHECK(btrim(content)<>''),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_community_comments_post ON community_comments(post_id,id);
CREATE TABLE community_likes (
 post_id BIGINT NOT NULL REFERENCES community_posts(id),
 user_id BIGINT NOT NULL REFERENCES users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(post_id,user_id)
);
