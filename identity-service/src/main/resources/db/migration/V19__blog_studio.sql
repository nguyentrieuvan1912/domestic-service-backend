CREATE TABLE blog_articles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slug VARCHAR(180) NOT NULL UNIQUE,
 title VARCHAR(240) NOT NULL,
 excerpt VARCHAR(800) NOT NULL DEFAULT '',
 category VARCHAR(40) NOT NULL CHECK (category IN ('CLEANING_TIPS','FAMILY_KNOWLEDGE')),
 cover_url TEXT NOT NULL DEFAULT '',
 author_name VARCHAR(160) NOT NULL,
 document TEXT NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED')),
 created_by BIGINT REFERENCES users(id),
 updated_by BIGINT REFERENCES users(id),
 version BIGINT NOT NULL DEFAULT 0,
 published_at TIMESTAMP WITH TIME ZONE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_blog_public ON blog_articles(status,published_at DESC);
CREATE TABLE blog_media (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_id BIGINT NOT NULL REFERENCES users(id),
 public_id VARCHAR(240) NOT NULL UNIQUE,
 resource_type VARCHAR(10) NOT NULL CHECK (resource_type IN ('image','video')),
 secure_url TEXT,
 status VARCHAR(20) NOT NULL DEFAULT 'RESERVED',
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
