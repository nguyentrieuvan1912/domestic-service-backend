CREATE TABLE community_comment_reports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 comment_id BIGINT NOT NULL REFERENCES community_comments(id),
 reporter_id BIGINT NOT NULL REFERENCES users(id),
 reason VARCHAR(20) NOT NULL CHECK(reason IN ('SPAM','MISINFORMATION','ABUSE','OTHER')),
 detail TEXT NOT NULL DEFAULT '' CHECK(length(detail)<=2000),
 status VARCHAR(12) NOT NULL DEFAULT 'OPEN' CHECK(status IN ('OPEN','RESOLVED','DISMISSED')),
 resolution VARCHAR(24) CHECK(resolution IN ('DELETE','BLOCK','DELETE_AND_BLOCK','DISMISS')),
 moderation_note TEXT,
 reviewed_by BIGINT REFERENCES users(id),
 reviewed_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(comment_id,reporter_id)
);
CREATE INDEX ix_comment_reports_queue ON community_comment_reports(status,id DESC);
