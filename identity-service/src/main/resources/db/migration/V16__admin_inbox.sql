CREATE TABLE admin_inbox_entries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 source VARCHAR(30) NOT NULL,
 source_key VARCHAR(160) NOT NULL,
 event_key VARCHAR(200) NOT NULL,
 state VARCHAR(100) NOT NULL,
 section VARCHAR(40) NOT NULL,
 target VARCHAR(255) NOT NULL,
 title VARCHAR(255) NOT NULL,
 summary TEXT NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 read_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(user_id,event_key)
);
CREATE INDEX ix_admin_inbox_user_id ON admin_inbox_entries(user_id,id DESC);
CREATE INDEX ix_admin_inbox_open ON admin_inbox_entries(user_id,section) WHERE active;
CREATE INDEX ix_admin_inbox_unread ON admin_inbox_entries(user_id) WHERE read_at IS NULL;
CREATE UNIQUE INDEX ux_admin_inbox_active_task ON admin_inbox_entries(user_id,source,source_key) WHERE active;
