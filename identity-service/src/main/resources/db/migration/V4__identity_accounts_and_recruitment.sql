ALTER TABLE users ADD COLUMN status_note TEXT NOT NULL DEFAULT '';
ALTER TABLE staffs ADD COLUMN account_rank VARCHAR(20) NOT NULL DEFAULT 'INTERN'
    CHECK (account_rank IN ('INTERN','STANDARD','PROFESSIONAL'));
CREATE TABLE account_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_account_sessions_user ON account_sessions(user_id);
CREATE TABLE staff_candidates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payload TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING','ONBOARDING','TRAINING','EVALUATION')),
    staff_id BIGINT UNIQUE REFERENCES staffs(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
