CREATE TABLE identity_push_devices (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id),
 token TEXT NOT NULL UNIQUE,
 session_hash VARCHAR(64) NOT NULL,
 platform VARCHAR(10) NOT NULL CHECK(platform IN ('android','ios')),
 enabled BOOLEAN NOT NULL DEFAULT true,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE identity_push_deliveries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 notification_id BIGINT NOT NULL REFERENCES notifications(id),
 device_id BIGINT NOT NULL REFERENCES identity_push_devices(id),
 status VARCHAR(12) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','TICKET','ACCEPTED','FAILED','EXPIRED','UNKNOWN')),
 attempts INTEGER NOT NULL DEFAULT 0,
 ticket_id TEXT,
 error_code VARCHAR(80),
 next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(notification_id,device_id)
);
