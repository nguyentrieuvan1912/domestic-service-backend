CREATE TABLE customer_wallets (
 customer_id BIGINT PRIMARY KEY, available_balance BIGINT NOT NULL DEFAULT 0 CHECK(available_balance>=0),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE customer_wallet_transactions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id BIGINT NOT NULL REFERENCES customer_wallets(customer_id),
 direction VARCHAR(10) NOT NULL CHECK(direction IN ('CREDIT','DEBIT')),
 transaction_type VARCHAR(20) NOT NULL CHECK(transaction_type IN ('TOP_UP','PAYMENT','REFUND')),
 amount BIGINT NOT NULL CHECK(amount>0), booking_id BIGINT,
 idempotency_key VARCHAR(160) NOT NULL UNIQUE, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER customer_wallet_ledger_immutable BEFORE UPDATE OR DELETE ON customer_wallet_transactions
 FOR EACH ROW EXECUTE FUNCTION reject_wallet_transaction_mutation();
CREATE INDEX ix_customer_wallet_history ON customer_wallet_transactions(customer_id,id DESC);
CREATE TABLE customer_topups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2000000000000) PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    amount BIGINT NOT NULL CHECK (amount BETWEEN 1 AND 100000000),
    booking_id BIGINT UNIQUE,
    request_key VARCHAR(160) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'CREATING'
        CHECK (status IN ('CREATING','PENDING','PAID','CANCELLED','EXPIRED','REVIEW')),
    provider_link_id VARCHAR(160) UNIQUE,
    checkout_url TEXT,
    qr_content TEXT,
    account_number VARCHAR(50),
    account_name VARCHAR(160),
    bank_bin VARCHAR(20),
    receiving_account_verified BOOLEAN NOT NULL DEFAULT false,
    description VARCHAR(25) NOT NULL,
    amount_received BIGINT NOT NULL DEFAULT 0 CHECK (amount_received >= 0),
    expires_at TIMESTAMPTZ NOT NULL DEFAULT now() + interval '15 minutes',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    verified_at TIMESTAMPTZ,
    paid_at TIMESTAMPTZ,
    UNIQUE(customer_id, request_key)
);

CREATE TABLE customer_topup_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_key VARCHAR(160) NOT NULL UNIQUE, topup_id BIGINT REFERENCES customer_topups(id),
 payload JSONB NOT NULL, received_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE customer_booking_payments (
 booking_id BIGINT PRIMARY KEY, customer_id BIGINT NOT NULL REFERENCES customer_wallets(customer_id),
 payment_id BIGINT NOT NULL UNIQUE REFERENCES payments(id), amount BIGINT NOT NULL CHECK(amount>0),
 refunded BOOLEAN NOT NULL DEFAULT false, reconciled_at TIMESTAMPTZ
);
