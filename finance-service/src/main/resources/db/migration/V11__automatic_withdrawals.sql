-- Only requests explicitly created in automatic mode may be dispatched by the job.
ALTER TABLE withdrawals ADD COLUMN automatic_requested BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE staff_bank_accounts ADD COLUMN verification_provider VARCHAR(20) NOT NULL DEFAULT 'MANUAL';
CREATE TABLE bank_lookup_attempts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 staff_id BIGINT NOT NULL,
 requested_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_bank_lookup_attempts_time ON bank_lookup_attempts(requested_at);
CREATE TABLE bank_lookup_proofs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 staff_id BIGINT NOT NULL,
 bank_code VARCHAR(30) NOT NULL,
 account_number VARCHAR(50) NOT NULL,
 account_holder VARCHAR(160) NOT NULL,
 provider VARCHAR(20) NOT NULL CHECK(provider='PAY2S'),
 provider_proof JSONB NOT NULL,
 checked_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_bank_lookup_proofs_owner ON bank_lookup_proofs(staff_id,bank_code,account_number,checked_at DESC);
CREATE TABLE bank_provider_verifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 bank_account_id BIGINT NOT NULL REFERENCES staff_bank_accounts(id),
 proof_id BIGINT NOT NULL REFERENCES bank_lookup_proofs(id),
 verified_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER bank_lookup_proofs_append_only BEFORE UPDATE OR DELETE ON bank_lookup_proofs
 FOR EACH ROW EXECUTE FUNCTION reject_wallet_transaction_mutation();
CREATE TRIGGER bank_provider_verifications_append_only BEFORE UPDATE OR DELETE ON bank_provider_verifications
 FOR EACH ROW EXECUTE FUNCTION reject_wallet_transaction_mutation();
