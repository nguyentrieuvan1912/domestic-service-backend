CREATE TABLE withdrawal_payouts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    withdrawal_id BIGINT NOT NULL UNIQUE REFERENCES withdrawals(id),
    reference_id VARCHAR(100) NOT NULL UNIQUE,
    idempotency_key VARCHAR(100) NOT NULL UNIQUE,
    provider_id VARCHAR(160) UNIQUE,
    status VARCHAR(20) NOT NULL CHECK (status IN ('SUBMITTING','PROCESSING','REVIEW','PAID','FAILED')),
    attempted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    checked_at TIMESTAMPTZ,
    provider_proof JSONB,
    message TEXT NOT NULL DEFAULT '',
    initiated_by BIGINT NOT NULL
);
CREATE INDEX ix_withdrawal_payouts_pending ON withdrawal_payouts(status,checked_at);
CREATE TABLE payout_money_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payout_id BIGINT NOT NULL REFERENCES withdrawal_payouts(id),
    account VARCHAR(40) NOT NULL CHECK(account IN ('STAFF_PAYABLE','BANK_DISBURSEMENTS')),
    direction VARCHAR(10) NOT NULL CHECK(direction IN ('DEBIT','CREDIT')),
    amount BIGINT NOT NULL CHECK(amount>0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(payout_id,account)
);
CREATE TRIGGER payout_money_entries_append_only BEFORE UPDATE OR DELETE ON payout_money_entries
    FOR EACH ROW EXECUTE FUNCTION reject_wallet_transaction_mutation();
