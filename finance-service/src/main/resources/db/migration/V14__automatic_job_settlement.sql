CREATE TABLE cash_job_debits (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 booking_id BIGINT NOT NULL,
 assignment_id BIGINT NOT NULL UNIQUE,
 staff_id BIGINT NOT NULL,
 slot INTEGER NOT NULL CHECK(slot >= 0),
 amount BIGINT NOT NULL CHECK(amount > 0),
 status VARCHAR(20) NOT NULL CHECK(status IN ('DEBITED','RELEASED','SETTLED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX cash_job_active_slot ON cash_job_debits(booking_id,slot) WHERE status IN ('DEBITED','SETTLED');
