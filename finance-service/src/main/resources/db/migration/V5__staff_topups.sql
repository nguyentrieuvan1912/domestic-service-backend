CREATE TABLE staff_topups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000) PRIMARY KEY,
    staff_id BIGINT NOT NULL,
    amount BIGINT NOT NULL CHECK (amount BETWEEN 2000 AND 1000000),
    request_key VARCHAR(160) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'CREATING'
        CHECK (status IN ('CREATING','PENDING','PAID','CANCELLED','EXPIRED','REVIEW')),
    provider_link_id VARCHAR(160) UNIQUE,
    checkout_url TEXT,
    qr_content TEXT,
    account_number VARCHAR(50),
    account_name VARCHAR(160),
    bank_bin VARCHAR(20),
    receiving_account_verified BOOLEAN NOT NULL DEFAULT false,
    description VARCHAR(25) NOT NULL,
    amount_received BIGINT NOT NULL DEFAULT 0 CHECK (amount_received >= 0),
    expires_at TIMESTAMPTZ NOT NULL DEFAULT now() + interval '15 minutes',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    verified_at TIMESTAMPTZ,
    paid_at TIMESTAMPTZ,
    UNIQUE(staff_id, request_key)
);
CREATE INDEX ix_topups_staff ON staff_topups(staff_id, created_at DESC);
ALTER TABLE wallet_transactions DROP CONSTRAINT wallet_transactions_transaction_type_check;
ALTER TABLE wallet_transactions ADD CONSTRAINT wallet_transactions_transaction_type_check
    CHECK (transaction_type IN ('EARNING','TIP','REWARD','PENALTY','WITHDRAWAL','HOLD','RELEASE','REVERSAL','TOP_UP'));
CREATE TABLE topup_provider_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_key VARCHAR(160) NOT NULL UNIQUE,
    topup_id BIGINT REFERENCES staff_topups(id),
    payload JSONB NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- These entries describe received topup money, not platform revenue.
CREATE TABLE topup_money_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topup_id BIGINT NOT NULL REFERENCES staff_topups(id),
    account VARCHAR(40) NOT NULL CHECK (account IN ('BANK_RECEIPTS','STAFF_PAYABLE')),
    direction VARCHAR(10) NOT NULL CHECK (direction IN ('DEBIT','CREDIT')),
    amount BIGINT NOT NULL CHECK (amount > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(topup_id, account)
);
CREATE TRIGGER topup_money_entries_append_only BEFORE UPDATE OR DELETE ON topup_money_entries
    FOR EACH ROW EXECUTE FUNCTION reject_wallet_transaction_mutation();
