CREATE TABLE bank_account_reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 bank_account_id BIGINT NOT NULL REFERENCES staff_bank_accounts(id),
 staff_id BIGINT NOT NULL,
 admin_id BIGINT NOT NULL,
 admin_name VARCHAR(160),
 old_status VARCHAR(20),
 new_status VARCHAR(20) NOT NULL CHECK(new_status IN ('VERIFIED','INACTIVE')),
 bank_code VARCHAR(30) NOT NULL,
 account_number VARCHAR(50) NOT NULL,
 account_holder VARCHAR(160) NOT NULL,
 verification_note TEXT NOT NULL,
 legacy BOOLEAN NOT NULL DEFAULT false,
 reviewed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_bank_account_reviews_history ON bank_account_reviews(bank_account_id,id DESC);
-- Preserve only facts already recorded by the old verification workflow; do not invent prior decisions or names.
INSERT INTO bank_account_reviews(bank_account_id,staff_id,admin_id,new_status,bank_code,account_number,account_holder,verification_note,legacy,reviewed_at)
 SELECT id,staff_id,verified_by,status,bank_code,account_number,account_holder,coalesce(verification_note,''),true,verified_at
 FROM staff_bank_accounts WHERE verified_by IS NOT NULL AND verified_at IS NOT NULL AND status IN ('VERIFIED','INACTIVE');
CREATE TRIGGER bank_account_reviews_append_only BEFORE UPDATE OR DELETE ON bank_account_reviews
 FOR EACH ROW EXECUTE FUNCTION reject_wallet_transaction_mutation();
