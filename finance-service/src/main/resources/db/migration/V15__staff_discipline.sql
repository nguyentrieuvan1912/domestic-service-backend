CREATE TABLE staff_discipline_policy (
 id BIGINT PRIMARY KEY CHECK(id=1), no_show_enabled BOOLEAN NOT NULL DEFAULT true,
 grace_minutes INTEGER NOT NULL DEFAULT 0 CHECK(grace_minutes BETWEEN 0 AND 120),
 penalty_amount BIGINT NOT NULL DEFAULT 5000 CHECK(penalty_amount BETWEEN 0 AND 1000000000),
 completion_bonus BIGINT NOT NULL DEFAULT 0 CHECK(completion_bonus BETWEEN 0 AND 1000000000),
 effective_from TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_by BIGINT
);
INSERT INTO staff_discipline_policy(id) VALUES(1);
CREATE TABLE staff_discipline_actions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, staff_id BIGINT NOT NULL, booking_id BIGINT,
 kind VARCHAR(30) NOT NULL CHECK(kind IN ('REWARD','PENALTY','WARN_THEN_PENALTY','WARNING')),
 violation_code VARCHAR(60) NOT NULL, violation_number INTEGER,
 amount BIGINT NOT NULL CHECK(amount>=0), reason TEXT NOT NULL, source VARCHAR(20) NOT NULL CHECK(source IN ('ADMIN','AUTOMATIC')),
 status VARCHAR(30) NOT NULL CHECK(status IN ('WARNING','PENDING_FUNDS','APPLIED')),
 request_key VARCHAR(160) NOT NULL UNIQUE, created_by BIGINT, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 applied_at TIMESTAMPTZ, adjustment_id BIGINT, ledger_id BIGINT, evidence TEXT NOT NULL DEFAULT ''
);
CREATE INDEX ix_staff_discipline_history ON staff_discipline_actions(staff_id,created_at);
CREATE TABLE staff_discipline_policy_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id BIGINT NOT NULL, before_value TEXT NOT NULL,
 after_value TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE FUNCTION retain_discipline_audit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Discipline audit records cannot be deleted'; END $$;
CREATE TRIGGER retain_discipline_actions BEFORE DELETE ON staff_discipline_actions FOR EACH ROW EXECUTE FUNCTION retain_discipline_audit();
CREATE TRIGGER retain_discipline_policies BEFORE UPDATE OR DELETE ON staff_discipline_policy_audit FOR EACH ROW EXECUTE FUNCTION retain_discipline_audit();
