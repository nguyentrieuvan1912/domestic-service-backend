CREATE TABLE manual_transfer_confirmations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payout_id BIGINT NOT NULL REFERENCES withdrawal_payouts(id),
    admin_id BIGINT NOT NULL,
    bank_reference VARCHAR(160) NOT NULL,
    recipient_note TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TRIGGER manual_transfer_confirmations_append_only BEFORE UPDATE OR DELETE ON manual_transfer_confirmations
    FOR EACH ROW EXECUTE FUNCTION reject_wallet_transaction_mutation();
