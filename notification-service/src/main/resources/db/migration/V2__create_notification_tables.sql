-- Prepared persistence model. No seed, producer, worker or push-provider integration.
-- user_id references Identity logically; there is no cross-database FK.
CREATE TABLE notification_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_service VARCHAR(80) NOT NULL CHECK (btrim(source_service) <> ''),
    event_key VARCHAR(200) NOT NULL CHECK (btrim(event_key) <> ''),
    event_type VARCHAR(80) NOT NULL CHECK (btrim(event_type) <> ''),
    payload JSONB NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(payload) = 'object'),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING','PROCESSING','PROCESSED','FAILED')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    last_error TEXT,
    received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    processed_at TIMESTAMPTZ,
    UNIQUE(source_service, event_key),
    CHECK (status <> 'PROCESSED' OR processed_at IS NOT NULL)
);
CREATE INDEX ix_notification_events_pending ON notification_events(status, received_at);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL CHECK (user_id > 0),
    target_role VARCHAR(20) CHECK (target_role IN ('CUSTOMER','STAFF','ADMIN')),
    event_id BIGINT REFERENCES notification_events(id),
    notification_type VARCHAR(80) NOT NULL CHECK (btrim(notification_type) <> ''),
    title VARCHAR(255) NOT NULL CHECK (btrim(title) <> ''),
    content TEXT NOT NULL CHECK (btrim(content) <> ''),
    reference_type VARCHAR(80),
    reference_id BIGINT,
    payload JSONB NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(payload) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    read_at TIMESTAMPTZ,
    UNIQUE(id, user_id),
    UNIQUE(event_id, user_id),
    CHECK (read_at IS NULL OR read_at >= created_at)
);
CREATE INDEX ix_notifications_user_created ON notifications(user_id, created_at DESC, id DESC);
CREATE INDEX ix_notifications_unread ON notifications(user_id) WHERE read_at IS NULL;
CREATE INDEX ix_notifications_event ON notifications(event_id);

CREATE TABLE notification_devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL CHECK (user_id > 0),
    device_key VARCHAR(200) NOT NULL CHECK (btrim(device_key) <> ''),
    platform VARCHAR(20) NOT NULL CHECK (platform IN ('ANDROID','IOS','WEB')),
    provider VARCHAR(20) NOT NULL CHECK (provider IN ('FCM','EXPO')),
    push_token TEXT NOT NULL CHECK (btrim(push_token) <> ''),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','REVOKED','INVALID')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ,
    UNIQUE(id, user_id),
    UNIQUE(provider, push_token),
    UNIQUE(user_id, device_key, provider)
);
CREATE INDEX ix_notification_devices_user ON notification_devices(user_id, status);

CREATE TABLE notification_deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    device_id BIGINT,
    channel VARCHAR(20) NOT NULL CHECK (channel IN ('IN_APP','PUSH')),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING','PROCESSING','SENT','DELIVERED','FAILED','CANCELLED')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    provider_reference TEXT,
    last_error TEXT,
    next_retry_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    CONSTRAINT fk_delivery_notification_owner FOREIGN KEY (notification_id, user_id)
        REFERENCES notifications(id, user_id),
    CONSTRAINT fk_delivery_device_owner FOREIGN KEY (device_id, user_id)
        REFERENCES notification_devices(id, user_id),
    UNIQUE NULLS NOT DISTINCT(notification_id, channel, device_id),
    CHECK ((channel = 'PUSH') = (device_id IS NOT NULL)),
    CHECK (status NOT IN ('SENT','DELIVERED') OR sent_at IS NOT NULL),
    CHECK (status <> 'DELIVERED' OR delivered_at IS NOT NULL)
);
CREATE INDEX ix_notification_deliveries_retry ON notification_deliveries(status, next_retry_at);
CREATE INDEX ix_notification_deliveries_device ON notification_deliveries(device_id);
COMMENT ON TABLE notifications IS 'Future notification-service inbox; active legacy inbox remains in identity_db until API cutover';
COMMENT ON TABLE notification_events IS 'Deduplicated incoming events; PROCESSED records require a processing timestamp';
COMMENT ON TABLE notification_devices IS 'Owned push endpoints; tokens are private provider credentials';
COMMENT ON TABLE notification_deliveries IS 'Delivery state per channel/device; recording PENDING does not mean successful delivery';
