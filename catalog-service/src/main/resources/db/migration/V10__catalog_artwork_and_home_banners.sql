CREATE TABLE catalog_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sha256 CHAR(64) NOT NULL UNIQUE,
    content BYTEA NOT NULL CHECK (octet_length(content) BETWEEN 1 AND 1572864)
);

CREATE TABLE home_banners (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id BIGINT NOT NULL REFERENCES services(id),
    title VARCHAR(80) NOT NULL,
    badge VARCHAR(30) NOT NULL DEFAULT '',
    description VARCHAR(140) NOT NULL DEFAULT '',
    button_label VARCHAR(24) NOT NULL DEFAULT '',
    theme VARCHAR(10) NOT NULL CHECK (theme IN ('BLUE', 'GREEN', 'ORANGE', 'NAVY')),
    layout VARCHAR(12) NOT NULL CHECK (layout IN ('SPLIT', 'FULL_IMAGE')),
    image_url TEXT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0 CHECK (sort_order BETWEEN 0 AND 9999),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

